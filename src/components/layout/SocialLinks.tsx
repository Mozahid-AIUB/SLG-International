/**
 * Renders nothing when no profiles are confirmed, so the footer never shows an
 * empty icon row while the client is still gathering links.
 */
export function SocialLinks({
  className = "",
  tone = "light",
}: {
  className?: string;
  /** "dark" for placement on the ink ground. */
  tone?: "light" | "dark";
}) {
  if (socials.length === 0) return null;

  const styles =
    tone === "dark"
      ? "border-white/20 text-paper-sunk hover:border-white/60 hover:text-white"
      : "border-rule-strong text-navy hover:border-accent hover:text-accent";

  const box = `flex h-10 w-10 items-center justify-center border transition-colors ${styles}`;

  return (
    <ul className={`flex flex-wrap items-center gap-3 ${className}`}>
      {socials.map((social) => {
        const icon = (
          <svg
            viewBox="0 0 24 24"
            aria-hidden="true"
            className="h-[18px] w-[18px] fill-current"
          >
            <path d={paths[social.id]} />
          </svg>
        );

        return (
          <li key={social.id}>
            {social.href ? (
              <a
                href={social.href}
                rel="noreferrer"
                target="_blank"
                aria-label={social.label}
                title={social.label}
                className={box}
              >
                {icon}
              </a>
            ) : (
              // Address not supplied yet. The icon is placed, but it is not a
              // link, so nobody clicks through to nothing.
              <span
                role="img"
                aria-label={social.label}
                title={social.label}
                className={box}
              >
                {icon}
              </span>
            )}
          </li>
        );
      })}
    </ul>
  );
}
